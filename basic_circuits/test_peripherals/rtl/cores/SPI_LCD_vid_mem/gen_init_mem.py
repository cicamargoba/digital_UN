VARIANT_LIST = ['ST7789', 'ILI9341', 'GC9A01', 'ILI9488']


def entries(lcd):
    out = []
    for kind, vals in SEQ[lcd]:
        if kind == 'delay':
            out.append(('delay', vals))
        else:
            out.append(('cmd', vals[0]))
            for p in vals[1:]:
                out.append(('param', p))
    return out


def spi_bytes(lcd):
    out = []
    for kind, val in entries(lcd):
        if kind == 'cmd':
            out.append((val, 0))
        elif kind == 'param':
            out.append((val, 1))
    return out


def write_variant(lcd):
    ent = entries(lcd)
    lines = []
    lines.append('module init_mem (')
    lines.append('    input      [7:0] addr,')
    lines.append('    output reg [9:0] data')
    lines.append(');')
    lines.append('localparam NUM_ENTRIES = %d;' % len(ent))
    lines.append('always @(*) begin')
    lines.append('    case (addr)')
    for i, (kind, val) in enumerate(ent):
        if kind == 'delay':
            lines.append("        8'd%-3d: data = {1'b1, 1'b0, 8'd%d};" % (i, val))
        elif kind == 'cmd':
            lines.append("        8'd%-3d: data = {1'b0, 1'b0, 8'h%02X};" % (i, val))
        else:
            lines.append("        8'd%-3d: data = {1'b0, 1'b1, 8'h%02X};" % (i, val))
    lines.append("        default: data = 10'h000;")
    lines.append('    endcase')
    lines.append('end')
    lines.append('endmodule')
    with open('init_mem_%s.vh' % lcd.lower(), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return len(ent)


def write_defs(counts):
    lines = []
    for i, lcd in enumerate(VARIANT_LIST):
        prefix = '`ifdef' if i == 0 else '`elsif'
        lines.append('%s LCD_%s' % (prefix, lcd))
        lines.append('`define LCD_INIT_MAX %d' % counts[lcd])
    lines.append('`else')
    lines.append('`define LCD_INIT_MAX %d' % counts['ST7789'])
    lines.append('`endif')
    with open('init_defs.vh', 'w') as f:
        f.write('\n'.join(lines) + '\n')


def write_selector():
    lines = []
    for i, lcd in enumerate(VARIANT_LIST):
        prefix = '`ifdef' if i == 0 else '`elsif'
        lines.append('%s LCD_%s' % (prefix, lcd))
        lines.append('`include "init_mem_%s.vh"' % lcd.lower())
    lines.append('`else')
    lines.append('`include "init_mem_st7789.vh"')
    lines.append('`endif')
    with open('init_mem.v', 'w') as f:
        f.write('\n'.join(lines) + '\n')


def check(lcd, logfile):
    import re
    pat = re.compile(r'spi_lcd: byte 0x([0-9A-Fa-f]{2}) dc=(\d)')
    got = []
    with open(logfile) as f:
        for line in f:
            m = pat.search(line)
            if m:
                got.append((int(m.group(1), 16), int(m.group(2))))
    exp = spi_bytes(lcd)
    if len(got) < len(exp) + 9:
        print('FAIL %s: only %d bytes captured, need %d' % (lcd, len(got), len(exp) + 9))
        return 1
    for i, (e, g) in enumerate(zip(exp, got)):
        if e != g:
            print('FAIL %s: byte %d expected 0x%02X dc=%d got 0x%02X dc=%d'
                  % (lcd, i, e[0], e[1], g[0], g[1]))
            return 1
    if got[len(exp)] != (0xDC, 0):
        print('FAIL %s: after init expected 0xDC dc=0 got 0x%02X dc=%d'
              % (lcd, got[len(exp)][0], got[len(exp)][1]))
        return 1
    stream = got[len(exp) + 1: len(exp) + 9]
    exp_stream = [(0xAA, 1), (0xBB, 1), (0xCC, 1), (0xDD, 1),
                  (0x11, 1), (0x22, 1), (0x33, 1), (0x44, 1)]
    if stream != exp_stream:
        print('FAIL %s: stream mismatch: %s' % (lcd, stream))
        return 1
    print('PASS %s: %d init bytes + 0xDC + 8 stream bytes verified'
          % (lcd, len(exp)))
    return 0


def main():
    if len(sys.argv) >= 4 and sys.argv[1] == '--check':
        sys.exit(check(sys.argv[2].upper(), sys.argv[3]))
    counts = {}
    for lcd in VARIANT_LIST:
        counts[lcd] = write_variant(lcd)
        print('%s: %d entries, %d spi bytes' % (lcd, counts[lcd], len(spi_bytes(lcd))))
    write_defs(counts)
    write_selector()


if __name__ == '__main__':
    main()
